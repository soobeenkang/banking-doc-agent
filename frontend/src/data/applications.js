function withStored(app) {
  if (app.status !== 'PASS') return app
  const stored = app.docs
    .filter((d) => d.result === '통과')
    .map((d) => ({
      name: d.name,
      pages: PAGES[d.name] || 1,
      fields: (FIELD_TEMPLATES[d.name]?.(app) || []).map(([label, value, level]) => ({ label, value, level })),
    }))
  return { ...app, stored }
}

